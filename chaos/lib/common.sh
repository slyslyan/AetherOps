#!/bin/bash
# common.sh — 公共函数库：日志、颜色、工具函数

# ============================================================
# 颜色定义
# ============================================================
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
BOLD='\033[1m'
NC='\033[0m'

# ============================================================
# 日志函数
# ============================================================
log_info()  { echo -e "${BLUE}[INFO]${NC}  $(date +%H:%M:%S) $*"; }
log_ok()    { echo -e "${GREEN}[OK]${NC}    $(date +%H:%M:%S) $*"; }
log_warn()  { echo -e "${YELLOW}[WARN]${NC}  $(date +%H:%M:%S) $*"; }
log_fail()  { echo -e "${RED}[FAIL]${NC}  $(date +%H:%M:%S) $*"; }
log_step()  { echo ""; echo -e "${BOLD}${BLUE}══════════════════════════════════════════════════${NC}"; echo -e "${BOLD}${BLUE}  $*${NC}"; echo -e "${BOLD}${BLUE}══════════════════════════════════════════════════${NC}"; }
log_title() { echo ""; echo -e "${CYAN}╔══════════════════════════════════════════════════╗${NC}"; echo -e "${CYAN}║  $*${NC}"; echo -e "${CYAN}╚══════════════════════════════════════════════════╝${NC}"; }

# ============================================================
# 错误处理
# ============================================================
die() {
    log_fail "$*"
    exit 1
}

# ============================================================
# 时间工具
# ============================================================
now_iso() { date -Iseconds; }
now_epoch() { date +%s; }

elapsed() {
    local start="$1"
    local end
    end=$(now_epoch)
    echo $((end - start))
}

# ============================================================
# 字符串工具（awk 浮点比较，因为 bash 不支持浮点）
# ============================================================
# 判断 $1 > $2
gt() { awk "BEGIN {exit !($1 > $2)}"; }
# 判断 $1 >= $2
ge() { awk "BEGIN {exit !($1 >= $2)}"; }
# 判断 $1 < $2
lt() { awk "BEGIN {exit !($1 < $2)}"; }
# 判断 $1 <= $2
le() { awk "BEGIN {exit !($1 <= $2)}"; }
# 取最大值
fmax() { awk "BEGIN {printf \"%f\", ($1 > $2 ? $1 : $2)}"; }
# 取最小值
fmin() { awk "BEGIN {printf \"%f\", ($1 < $2 ? $1 : $2)}"; }
